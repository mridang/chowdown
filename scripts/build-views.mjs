/**
 * Bundles each MCP Apps View (a React component mounted by src/views/<name>.tsx)
 * into a single self-contained HTML document and writes it as a TypeScript
 * module. The MCP server imports those modules and serves the HTML from
 * `resources/read` as the `ui://` resource bodies.
 *
 * The View is a real browser React app: esbuild bundles React + the ext-apps
 * client bridge inline (the iframe has no module loader of its own), so the
 * output is one HTML file with `<div id="root">` and an inline module script —
 * exactly the shape the MCP Apps spec expects, and the shape the default
 * Content-Security-Policy (`script-src 'unsafe-inline'`, nothing external)
 * allows without declaring any origin.
 *
 * Each generated module exports:
 *   - `html`: the document,
 *   - `contentHash`: the SHA-256 (hex) of that document. The server derives the
 *     View's `ui://` address from it, so hosts, which cache a View by its
 *     address, fetch it again exactly when it changes.
 *
 * Run via `devbox run npm run build:views` (invoked before the Next build).
 */

import { build as esbuildBuild } from 'esbuild';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outDir = path.resolve(root, 'dist/views');

/** The app's name, as `src/utils/site.ts` gives it, for the page titles. */
const SITE_NAME =
  /export const SITE_NAME = '([^']+)'/.exec(
    // eslint-disable-next-line n/no-sync -- sync is fine in a script or bootstrap
    readFileSync(path.resolve(root, 'src/utils/site.ts'), 'utf8'),
  )?.[1] ?? '';

/**
 * The Views to bundle: every entry point `src/views/<name>.tsx` that mounts a
 * component of its own (`src/views/<name>-view.tsx`), titled with the app's
 * name and the View's ("chowdown recipe card").
 */
// eslint-disable-next-line n/no-sync -- sync is fine in a script or bootstrap
const VIEWS = readdirSync(path.resolve(root, 'src/views'))
  .filter((file) => file.endsWith('-view.tsx'))
  .map((file) => file.slice(0, -'-view.tsx'.length))
  // eslint-disable-next-line n/no-sync -- sync is fine in a script or bootstrap
  .filter((name) => existsSync(path.resolve(root, `src/views/${name}.tsx`)))
  .toSorted()
  .map((name) => ({
    name,
    title: `${SITE_NAME} ${name.replaceAll('-', ' ')}`,
  }));

/**
 * Zod ships message catalogues for 50 languages and exposes them all as one
 * namespace, which the bundler cannot split apart: they were about 190 KB of
 * every View. The ext-apps client only ever uses the default (English) one, so
 * the namespace is replaced by a module that exports just that.
 */
const slimZodLocales = {
  name: 'slim-zod-locales',
  setup(build) {
    build.onLoad(
      { filter: /zod[\\/]v4[\\/]locales[\\/]index\.js$/ },
      (args) => ({
        contents: "export { default as en } from './en.js';",
        resolveDir: path.dirname(args.path),
        loader: 'js',
      }),
    );
  },
};

// eslint-disable-next-line n/no-sync -- sync is fine in a script or bootstrap
mkdirSync(outDir, { recursive: true });

for (const { name, title } of VIEWS) {
  const result = await esbuildBuild({
    entryPoints: [path.resolve(root, `src/views/${name}.tsx`)],
    bundle: true,
    format: 'iife',
    minify: true,
    jsx: 'automatic',
    platform: 'browser',
    target: 'es2022',
    write: false,
    define: { 'process.env.NODE_ENV': '"production"' },
    plugins: [slimZodLocales],
  });

  const js = result.outputFiles[0].text;
  const html = `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="light dark"><title>${title}</title></head>
<body><div id="root"></div><script type="module">${js}</script></body>
</html>`;
  const contentHash = createHash('sha256').update(html).digest('hex');

  // eslint-disable-next-line n/no-sync -- sync is fine in a script or bootstrap
  writeFileSync(
    path.resolve(outDir, `${name}.ts`),
    `// AUTO-GENERATED by scripts/build-views.mjs — do not edit by hand.\n` +
      `export const html = ${JSON.stringify(html)};\n` +
      `export const contentHash = ${JSON.stringify(contentHash)};\n`,
  );
  console.log(
    `built view "${name}" → ${(html.length / 1024).toFixed(1)} KB (${contentHash.slice(0, 12)})`,
  );
}
