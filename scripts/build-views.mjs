/**
 * Bundles each MCP Apps View (a React component in src/views/<name>.tsx) into a
 * single self-contained HTML document and writes it as a TypeScript module that
 * exports the HTML string. The MCP server imports those strings and serves them
 * from `resources/read` as the `ui://` resource bodies.
 *
 * The View is a real browser React app: esbuild bundles React + the ext-apps
 * client bridge inline (the iframe has no module loader of its own), so the
 * output is one HTML file with `<div id="root">` and an inline module script —
 * exactly the shape the MCP Apps spec expects.
 *
 * Run via `devbox run build:views` (invoked before the Next build).
 */

import * as esbuild from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'src/views/generated');

/** View entry points (src/views/<name>.tsx) to bundle. */
const VIEWS = ['recipe-card', 'recipe-list'];

mkdirSync(outDir, { recursive: true });

for (const view of VIEWS) {
  const result = await esbuild.build({
    entryPoints: [resolve(root, `src/views/${view}.tsx`)],
    bundle: true,
    format: 'iife',
    minify: true,
    jsx: 'automatic',
    platform: 'browser',
    target: 'es2022',
    write: false,
    define: { 'process.env.NODE_ENV': '"production"' },
  });

  const js = result.outputFiles[0].text;
  const html = `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head>
<body><div id="root"></div><script type="module">${js}</script></body>
</html>`;

  writeFileSync(
    resolve(outDir, `${view}.ts`),
    `// AUTO-GENERATED by scripts/build-views.mjs — do not edit by hand.\n` +
      `/* eslint-disable */\n` +
      `export const html = ${JSON.stringify(html)};\n`,
  );
  console.log(`built view "${view}" → ${(html.length / 1024).toFixed(1)} KB`);
}
