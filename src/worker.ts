// @ts-nocheck — this is the wrangler entry, not part of the Next app. It
// statically imports `../.open-next/worker.js`, which OpenNext only emits
// during `opennextjs-cloudflare build` (after `next build`). That module
// therefore can't exist at type-check time, so this one file cannot be
// type-checked by construction; wrangler resolves the import at bundle time,
// once the file has been generated. Everything it does is in `lib/http/serve.ts`
// and `lib/worker-extras.ts`, which are checked and tested.
/**
 * @packageDocumentation
 *
 * Production Worker entry point.
 *
 * The Next.js handler is generated by OpenNext into `.open-next/worker.js`.
 * This file forwards `fetch` to `serve` (the security headers, and whatever the
 * app adds in `lib/http/extras.ts`; see `lib/http/serve.ts`). It is a thin
 * wrapper (rather than pointing `wrangler.jsonc` straight at the generated file)
 * so Worker-level additions have an obvious home: `lib/worker-extras.ts` holds
 * this app's cron handler and the Workflow or Durable Object classes it exports,
 * and has the same shape in every app.
 *
 * Deployment glue:
 *
 *   1. `wrangler.jsonc` -> `main` set to this file (`src/worker.ts`).
 *   2. `next build && opennextjs-cloudflare build` produces
 *      `.open-next/worker.js`.
 *   3. `wrangler deploy` bundles this file.
 */

import openNextHandler from '../.open-next/worker.js';
import { serve } from './core/http/serve';
import extraHandlers from './core/worker-extras';

export * from './core/worker-extras';

/** The Worker itself. */
const handler: ExportedHandler<CloudflareEnv> = {
  async fetch(request, env, ctx) {
    return serve(request, env, ctx, { app: openNextHandler });
  },
  ...extraHandlers,
};

export default handler;
